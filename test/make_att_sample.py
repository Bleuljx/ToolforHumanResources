D = lambda day: datetime.date(2026, 10, day)
T = lambda s: datetime.datetime.strptime(s, "%H:%M").time()


def plain(ws, headers, rows, sheet_name=None):
    if sheet_name:
        ws.title = sheet_name
    for c, h in enumerate(headers, 1):
        ws.cell(row=1, column=c).value = h
        ws.cell(row=1, column=c).font = Font(name="宋体", size=12, bold=True)
        ws.cell(row=1, column=c).alignment = Alignment(horizontal="center")
    for r, row in enumerate(rows, 2):
        for c, v in enumerate(row, 1):
            ws.cell(row=r, column=c).value = v
            ws.cell(row=r, column=c).font = Font(name="宋体", size=11)
            ws.cell(row=r, column=c).alignment = Alignment(horizontal="center")


